CREATE SCHEMA IF NOT EXISTS dw_floco;

DROP TABLE IF EXISTS dw_floco.fato_venda CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_tempo CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_produto CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_categoria CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_laboratorio CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_cliente CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_loja CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_cidade CASCADE;
DROP TABLE IF EXISTS dw_floco.dim_estado CASCADE;

CREATE TABLE dw_floco.dim_tempo (
    sk_tempo    INT          PRIMARY KEY,
    data        DATE         NOT NULL,
    dia         INT          NOT NULL,
    mes         INT          NOT NULL,
    nome_mes    VARCHAR(15)  NOT NULL,
    trimestre   INT          NOT NULL,
    semestre    INT          NOT NULL,
    ano         INT          NOT NULL,
    dia_semana  VARCHAR(15)  NOT NULL,
    CONSTRAINT uk_dim_tempo_data UNIQUE (data),
    CONSTRAINT ck_dim_tempo_dia CHECK (dia BETWEEN 1 AND 31),
    CONSTRAINT ck_dim_tempo_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_tempo_trimestre CHECK (trimestre BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_tempo_semestre CHECK (semestre BETWEEN 1 AND 2)
);

CREATE TABLE dw_floco.dim_categoria (
    sk_categoria  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem     BIGINT       NOT NULL,
    nome          VARCHAR(80)  NOT NULL,
    CONSTRAINT uk_dim_categoria_origem UNIQUE (id_origem)
);

CREATE TABLE dw_floco.dim_laboratorio (
    sk_laboratorio  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem       BIGINT        NOT NULL,
    nome            VARCHAR(120)  NOT NULL,
    CONSTRAINT uk_dim_laboratorio_origem UNIQUE (id_origem)
);

CREATE TABLE dw_floco.dim_produto (
    sk_produto      BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem       BIGINT        NOT NULL,
    nome            VARCHAR(120)  NOT NULL,
    apresentacao    VARCHAR(120),
    sk_categoria    BIGINT        NOT NULL REFERENCES dw_floco.dim_categoria (sk_categoria),
    sk_laboratorio  BIGINT        NOT NULL REFERENCES dw_floco.dim_laboratorio (sk_laboratorio),
    CONSTRAINT uk_dim_produto_origem UNIQUE (id_origem)
);

CREATE TABLE dw_floco.dim_estado (
    sk_estado  BIGINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uf         CHAR(2)  NOT NULL,
    CONSTRAINT uk_dim_estado_uf UNIQUE (uf)
);

CREATE TABLE dw_floco.dim_cidade (
    sk_cidade  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sk_estado  BIGINT       NOT NULL REFERENCES dw_floco.dim_estado (sk_estado),
    nome       VARCHAR(80)  NOT NULL,
    CONSTRAINT uk_dim_cidade_estado_nome UNIQUE (sk_estado, nome)
);

CREATE TABLE dw_floco.dim_loja (
    sk_loja    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem  BIGINT        NOT NULL,
    nome       VARCHAR(120)  NOT NULL,
    sk_cidade  BIGINT        NOT NULL REFERENCES dw_floco.dim_cidade (sk_cidade),
    CONSTRAINT uk_dim_loja_origem UNIQUE (id_origem)
);

CREATE TABLE dw_floco.dim_cliente (
    sk_cliente       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origem        BIGINT        NOT NULL,
    nome             VARCHAR(120)  NOT NULL,
    cidade           VARCHAR(80),
    uf               CHAR(2),
    inicio_vigencia  TIMESTAMP     NOT NULL,
    fim_vigencia     TIMESTAMP,
    atual            BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_dim_cliente_versao UNIQUE (id_origem, inicio_vigencia),
    CONSTRAINT ck_dim_cliente_vigencia CHECK (fim_vigencia IS NULL OR fim_vigencia > inicio_vigencia),
    CONSTRAINT ck_dim_cliente_atual CHECK ((atual AND fim_vigencia IS NULL) OR (NOT atual AND fim_vigencia IS NOT NULL))
);

CREATE UNIQUE INDEX uk_dim_cliente_versao_atual ON dw_floco.dim_cliente (id_origem) WHERE atual;

CREATE TABLE dw_floco.fato_venda (
    sk_fato               BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_venda_id_origem  BIGINT         NOT NULL,
    venda_id_origem       BIGINT         NOT NULL,
    sk_tempo              INT            NOT NULL REFERENCES dw_floco.dim_tempo (sk_tempo),
    sk_produto            BIGINT         NOT NULL REFERENCES dw_floco.dim_produto (sk_produto),
    sk_cliente            BIGINT         NOT NULL REFERENCES dw_floco.dim_cliente (sk_cliente),
    sk_loja               BIGINT         NOT NULL REFERENCES dw_floco.dim_loja (sk_loja),
    quantidade            INT            NOT NULL,
    valor_bruto           NUMERIC(14,2)  NOT NULL,
    desconto_valor        NUMERIC(14,2)  NOT NULL DEFAULT 0,
    valor_liquido         NUMERIC(14,2)  NOT NULL,
    CONSTRAINT uk_fato_venda_item UNIQUE (item_venda_id_origem),
    CONSTRAINT ck_fato_venda_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_fato_venda_desconto CHECK (desconto_valor >= 0 AND desconto_valor <= valor_bruto),
    CONSTRAINT ck_fato_venda_liquido CHECK (valor_liquido = valor_bruto - desconto_valor)
);

CREATE INDEX ix_fato_venda_tempo ON dw_floco.fato_venda (sk_tempo);
CREATE INDEX ix_fato_venda_produto ON dw_floco.fato_venda (sk_produto);
CREATE INDEX ix_fato_venda_cliente ON dw_floco.fato_venda (sk_cliente);
CREATE INDEX ix_fato_venda_loja ON dw_floco.fato_venda (sk_loja);
CREATE INDEX ix_dim_produto_categoria ON dw_floco.dim_produto (sk_categoria);
CREATE INDEX ix_dim_produto_laboratorio ON dw_floco.dim_produto (sk_laboratorio);
CREATE INDEX ix_dim_loja_cidade ON dw_floco.dim_loja (sk_cidade);
CREATE INDEX ix_dim_cidade_estado ON dw_floco.dim_cidade (sk_estado);
